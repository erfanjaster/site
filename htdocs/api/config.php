declare(strict_types=1);

define('FI_VERSION', '2.0.0');

// Project root = the htdocs folder (parent of api/). Auto-detected.
define('FI_ROOT', dirname(__DIR__));

// Writable storage (DB, logs, backups). Web access is denied by
// storage/.htaccess (Apache/LiteSpeed) and storage/web.config (IIS).
define('FI_STORAGE', FI_ROOT . '/storage');

/**
 * Resolve the database path. Priority:
 *   1. storage/.db-name.php  → return '<random>.sqlite'  (written by installer)
 *   2. legacy storage/game.db                            (migrated v1 installs)
 *   3. generate a fresh random name and persist it       (first run, zero-config)
 */
function fi_resolve_db(): string
{
    $dir = FI_STORAGE;
    $nameFile = $dir . '/.db-name.php';
    if (is_file($nameFile)) {
        $name = require $nameFile;
        if (is_string($name) && preg_match('/^[A-Za-z0-9._-]+$/', $name)) {
            return $dir . '/' . $name;
        }
    }
    if (is_file($dir . '/game.db')) {
        return $dir . '/game.db';
    }
    if (!is_dir($dir)) {
        @mkdir($dir, 0775, true);
    }
    $name = 'fi-' . bin2hex(random_bytes(9)) . '.sqlite';
    $php = "<?php\n// Random database filename — generated by the installer.\n"
         . "// Renaming the DB file? Update this file to match. Never delete it while the DB exists.\n"
         . 'return ' . var_export($name, true) . ";\n";
    if (@file_put_contents($nameFile, $php, LOCK_EX) !== false) {
        @chmod($nameFile, 0640);
    }
    return $dir . '/' . $name;
}
define('FI_DB', fi_resolve_db());

