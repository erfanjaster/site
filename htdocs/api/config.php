 *   ├── admin/      ← admin panel UI
 *   ├── jobs/       ← cron scripts (CLI only, web access denied)
 *   └── storage/    ← SQLite DB + logs + backups (web access DENIED)
 *
 * Because the database must now live *inside* the web root, it is protected
 * by four independent layers — see the "htdocs security" notes in the
 * install guide. The important one configured here: the DB filename is
 * RANDOM (generated once by install.php and stored in storage/.db-name.php),
 * so even if a server ignores .htaccess rules, the file cannot be guessed.
 *
 * You normally do NOT need to edit paths — they auto-resolve.
